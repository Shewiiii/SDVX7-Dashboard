from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from unlock_search.ts_literals import LiteralReader

ROOT = Path(__file__).resolve().parent
PLUGIN = ROOT.parent / "asphyxia-core-win-x64/plugins/sdvx@asphyxia"
OUTPUT = ROOT / "public/game-data/skill-analyzer.js"


def build_courses(plugin: Path) -> list[dict[str, Any]]:
    seasons = LiteralReader(plugin / "data").constant("COURSES7")
    courses = []
    identifiers = set()

    for season in seasons:
        for course in season["courses"]:
            identifier = f"7:{season['id']}:{course['id']}"
            if identifier in identifiers:
                raise ValueError(f"Duplicate course: {identifier}")
            identifiers.add(identifier)

            level = course["level"]
            if level:
                rank = "∞" if level == 12 else f"{level:02d}"
                season_name = re.sub(r"^SKILL ANALYZER\s*", "", season["name"])
                folder = f"Level {rank} · {season_name}"
            else:
                folder = course["name"]

            tracks = []
            positions = set()
            for track in sorted(course["tracks"], key=lambda item: item["no"]):
                mid, diff, position = track["mid"], track["mty"], track["no"]
                if (
                    type(mid) is not int
                    or not 0 < mid <= 10000000
                    or type(diff) is not int
                    or not 0 <= diff <= 5
                    or type(position) is not int
                    or position < 0
                    or position in positions
                ):
                    raise ValueError(f"Invalid track in course: {identifier}")
                positions.add(position)
                tracks.append({"music_id": mid, "diff_idx": diff})

            if not tracks:
                raise ValueError(f"Empty course: {identifier}")

            courses.append(
                {
                    "id": identifier,
                    "folder": folder,
                    "level": level,
                    "season": season["name"],
                    "name": course["name"],
                    "tracks": tracks,
                }
            )

    if not courses:
        raise ValueError("No Skill analyzer courses found")
    return courses


def main() -> None:
    print("Refreshing local Skill analyzer sources...", flush=True)
    courses = build_courses(PLUGIN)
    content = (
        "// Generated by update_skill_analyzer.py\n"
        "export const SKILL_ANALYZER_COURSES = "
        + json.dumps(courses, ensure_ascii=False, indent=4)
        + ";\n"
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    temporary = OUTPUT.with_suffix(".tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(OUTPUT)

    print("Skill analyzer catalog updated.")


if __name__ == "__main__":
    print(
        "This script will update Skill analyzer courses from Asphyxia. "
        "Make sure your Nabla plugin is up-to-date ! https://github.com/22vv0/asphyxia_plugins"
    )
    print("Requires asphyxia-core-win-x64 folder in your game's root folder")
    main()
